"""
URDF -> MJCF conversion that mirrors the Gazebo (gz-sim / DART) setup of the
robot as closely as MuJoCo allows.

The URDF (``simulation/urdf/spot.urdf``, generated by xacro) is parsed with
``xml.etree``: links (inertials, collision primitives), joints (origin, axis,
limits, damping / friction), ``<gazebo reference>`` friction (feet mu 1.0) and
the JointPositionController plugin blocks (``use_velocity_commands``,
``cmd_max``, ``initial_position``).  Visual meshes are ignored.

Mapping to MuJoCo
-----------------
* links -> bodies (``base_link`` gets a free joint); fixed joints -> bodies
  without a joint (welded, e.g. the massless feet that carry the foot spheres;
  sdformat lumps them into the lower leg - same rigid body);
* inertials -> ``<inertial pos quat mass fullinertia>`` (exactly the URDF values);
* collisions -> box / cylinder / sphere geoms (group 1, robot); meshes skipped;
* revolute joints -> hinge joints with the URDF range, damping and
  ``frictionloss`` = URDF friction;
* every joint gets one actuator emulating its gz JointPositionController
  (:class:`physics.sim.GzServo` computes the command every gz step of 1 ms):

  - PID force mode (``use_velocity_commands`` false - the URDF contract since
    the physics check): a plain motor whose force is the gz::math::PID output
    ``-(p e + d de/dt)`` (clamped to ``cmd_min .. cmd_max`` = +-effort) held
    over the gz step, like DART applies a joint force command for one step;
  - velocity mode (what-if ``servo="velocity"``, the former contract): a
    velocity actuator ``kv * (ctrl - qvel)`` limited to the URDF ``effort``
    with ``ctrl = clamp((q_target - q) / dt_gz, -cmd_max, cmd_max)``
    (DART SERVO actuator: a velocity constraint bounded by the joint effort).
    MuJoCo has no force-bounded velocity constraint; the actuator is
    integrated implicitly (``implicitfast``) and a stiff velocity servo
    pressing a foot into a soft contact limit-cycles unless
    ``kv * dt_mujoco`` stays below ~0.05 N m s.

  MuJoCo therefore runs at 0.1 ms (10 substeps per 1 ms gz step, the command
  held over the gz step) with ``kv = 500`` for the velocity mode;
* self collision off (SDF default for models): robot geoms ``contype=1,
  conaffinity=0`` collide with terrain (``contype=conaffinity=1``) only;
* friction: DART combines the friction of two shapes with ``min(mu_a, mu_b)``
  whereas MuJoCo takes the max.  Terrain geoms therefore get ``priority=1``
  (their parameters win) and ``mu = min(mu_terrain, mu_robot)``;
* contacts: elliptic friction cones with ``impratio`` 10 and a stiff
  ``solref`` (2 ms) approximate DART's hard (LCP) contacts and non-creeping
  friction; joint limits use a 2 ms solref as well.
"""
from __future__ import annotations

import math
import os
import xml.etree.ElementTree as ET
from dataclasses import dataclass, field
from typing import Dict, List, Optional, Sequence, Tuple

import numpy as np

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.abspath(os.path.join(HERE, "..", ".."))
DEFAULT_URDF = os.path.join(ROOT, "simulation", "urdf", "spot.urdf")

ROBOT_GROUP = 1           # geom group of robot geoms (excluded from depth rays)
TERRAIN_GROUP = 0

# MuJoCo solver settings that approximate DART (see module docstring)
GZ_DT = 0.001             # plant.sdf max_step_size (servo command update period)
SUBSTEPS = 10             # MuJoCo steps per gz step (see the docstring: servo / contact stability)
PHYSICS_DT = GZ_DT / SUBSTEPS
CONTACT_SOLREF = (0.002, 1.0)
CONTACT_SOLIMP = (0.95, 0.99, 0.001, 0.5, 2.0)
LIMIT_SOLREF = (0.002, 1.0)
SERVO_KV = 500.0
IMPRATIO = 10.0


# ---------------------------------------------------------------------------
# small math helpers
# ---------------------------------------------------------------------------
def rpy_to_quat(r: float, p: float, y: float) -> Tuple[float, float, float, float]:
    """URDF rpy (fixed axes X, Y, Z: R = Rz(y) Ry(p) Rx(r)) -> MuJoCo quat (w, x, y, z)."""
    cr, sr = math.cos(r / 2), math.sin(r / 2)
    cp, sp = math.cos(p / 2), math.sin(p / 2)
    cy, sy = math.cos(y / 2), math.sin(y / 2)
    return (cr * cp * cy + sr * sp * sy,
            sr * cp * cy - cr * sp * sy,
            cr * sp * cy + sr * cp * sy,
            cr * cp * sy - sr * sp * cy)


def rpy_to_matrix(r: float, p: float, y: float) -> np.ndarray:
    """URDF rpy -> rotation matrix Rz(y) Ry(p) Rx(r)."""
    cr, sr, cp, sp, cy, sy = math.cos(r), math.sin(r), math.cos(p), math.sin(p), math.cos(y), math.sin(y)
    return np.array([[cy * cp, cy * sp * sr - sy * cr, cy * sp * cr + sy * sr],
                     [sy * cp, sy * sp * sr + cy * cr, sy * sp * cr - cy * sr],
                     [-sp, cp * sr, cp * cr]])


def _vec(text: Optional[str], n: int = 3, default: float = 0.0) -> Tuple[float, ...]:
    if text is None:
        return tuple([default] * n)
    vals = [float(v) for v in text.split()]
    if len(vals) != n:
        raise ValueError(f"expected {n} numbers, got {text!r}")
    return tuple(vals)


def _fmt(vals: Sequence[float]) -> str:
    return " ".join(f"{float(v):.10g}" for v in vals)


# ---------------------------------------------------------------------------
# URDF model
# ---------------------------------------------------------------------------
@dataclass
class Origin:
    xyz: Tuple[float, float, float] = (0.0, 0.0, 0.0)
    rpy: Tuple[float, float, float] = (0.0, 0.0, 0.0)

    @classmethod
    def parse(cls, el: Optional[ET.Element]) -> "Origin":
        if el is None:
            return cls()
        return cls(_vec(el.get("xyz")), _vec(el.get("rpy")))

    @property
    def quat(self):
        return rpy_to_quat(*self.rpy)


@dataclass
class Inertial:
    origin: Origin
    mass: float
    inertia: Tuple[float, float, float, float, float, float]   # ixx iyy izz ixy ixz iyz


@dataclass
class Collision:
    name: str
    origin: Origin
    kind: str                    # box | cylinder | sphere | mesh
    size: Tuple[float, ...]      # box: (x, y, z) full sizes, cylinder: (radius, length), sphere: (radius,)


@dataclass
class Link:
    name: str
    inertial: Optional[Inertial] = None
    collisions: List[Collision] = field(default_factory=list)
    mu: Optional[float] = None   # <gazebo reference> mu1


@dataclass
class Joint:
    name: str
    type: str
    parent: str
    child: str
    origin: Origin
    axis: Tuple[float, float, float] = (1.0, 0.0, 0.0)
    lower: float = -math.inf
    upper: float = math.inf
    effort: float = math.inf
    velocity: float = math.inf
    damping: float = 0.0
    friction: float = 0.0


@dataclass
class ServoSpec:
    """gz JointPositionController parameters of one joint (gz-sim defaults)."""
    joint: str
    use_velocity_commands: bool = False
    cmd_max: float = math.inf            # gz default: numeric limits (no output clamp)
    cmd_min: float = -math.inf
    initial_position: float = 0.0
    p_gain: float = 1.0
    i_gain: float = 0.0
    d_gain: float = 0.0
    i_max: float = 1.0
    i_min: float = -1.0
    cmd_offset: float = 0.0

    @property
    def mode(self) -> str:
        return "velocity" if self.use_velocity_commands else "force"


@dataclass
class RobotDescription:
    name: str
    links: Dict[str, Link]
    joints: Dict[str, Joint]
    servos: Dict[str, ServoSpec]
    root: str

    def children(self, link: str) -> List[Joint]:
        return [j for j in self.joints.values() if j.parent == link]

    @property
    def total_mass(self) -> float:
        return float(sum(l.inertial.mass for l in self.links.values() if l.inertial is not None))

    def actuated_joints(self) -> List[Joint]:
        return [j for j in self.joints.values() if j.type in ("revolute", "continuous", "prismatic")]


def parse_urdf(path: str = DEFAULT_URDF) -> RobotDescription:
    """Parse the URDF (no xacro: pass the generated ``spot.urdf``)."""
    tree = ET.parse(path)
    robot = tree.getroot()
    links: Dict[str, Link] = {}
    for el in robot.findall("link"):
        link = Link(el.get("name"))
        ine = el.find("inertial")
        if ine is not None:
            m = float(ine.find("mass").get("value"))
            I = ine.find("inertia")
            vals = tuple(float(I.get(k, "0")) for k in ("ixx", "iyy", "izz", "ixy", "ixz", "iyz"))
            link.inertial = Inertial(Origin.parse(ine.find("origin")), m, vals)
        for i, col in enumerate(el.findall("collision")):
            g = col.find("geometry")
            name = col.get("name") or f"{link.name}_collision_{i}"
            origin = Origin.parse(col.find("origin"))
            if g.find("box") is not None:
                link.collisions.append(Collision(name, origin, "box", _vec(g.find("box").get("size"))))
            elif g.find("cylinder") is not None:
                c = g.find("cylinder")
                link.collisions.append(Collision(name, origin, "cylinder",
                                                 (float(c.get("radius")), float(c.get("length")))))
            elif g.find("sphere") is not None:
                link.collisions.append(Collision(name, origin, "sphere",
                                                 (float(g.find("sphere").get("radius")),)))
            else:
                link.collisions.append(Collision(name, origin, "mesh", ()))
        links[link.name] = link
    joints: Dict[str, Joint] = {}
    for el in robot.findall("joint"):
        j = Joint(el.get("name"), el.get("type"), el.find("parent").get("link"), el.find("child").get("link"),
                  Origin.parse(el.find("origin")))
        ax = el.find("axis")
        if ax is not None:
            j.axis = _vec(ax.get("xyz"))
        lim = el.find("limit")
        if lim is not None:
            j.lower = float(lim.get("lower", "-inf"))
            j.upper = float(lim.get("upper", "inf"))
            j.effort = float(lim.get("effort", "inf"))
            j.velocity = float(lim.get("velocity", "inf"))
        dyn = el.find("dynamics")
        if dyn is not None:
            j.damping = float(dyn.get("damping", "0"))
            j.friction = float(dyn.get("friction", "0"))
        joints[j.name] = j
    servos: Dict[str, ServoSpec] = {}
    for gz in robot.findall("gazebo"):
        ref = gz.get("reference")
        if ref is not None and ref in links:
            mu1 = gz.find("mu1")
            if mu1 is not None:
                links[ref].mu = float(mu1.text)
        for plug in gz.findall("plugin"):
            if "JointPositionController" not in (plug.get("name") or ""):
                continue

            def txt(tag, default):
                e = plug.find(tag)
                return e.text.strip() if e is not None and e.text else default
            s = ServoSpec(txt("joint_name", ""),
                          txt("use_velocity_commands", "false").lower() in ("1", "true"),
                          float(txt("cmd_max", "inf")), float(txt("cmd_min", "-inf")),
                          float(txt("initial_position", "0")),
                          float(txt("p_gain", "1")), float(txt("i_gain", "0")), float(txt("d_gain", "0")),
                          float(txt("i_max", "1")), float(txt("i_min", "-1")), float(txt("cmd_offset", "0")))
            servos[s.joint] = s
    children = {j.child for j in joints.values()}
    roots = [n for n in links if n not in children]
    if len(roots) != 1:
        raise ValueError(f"URDF must have exactly one root link, found {roots}")
    return RobotDescription(robot.get("name"), links, joints, servos, roots[0])


# ---------------------------------------------------------------------------
# MJCF
# ---------------------------------------------------------------------------
def _geom_xml(col: Collision, mu: float, indent: str) -> str:
    q = col.origin.quat
    common = (f'name="{col.name}" pos="{_fmt(col.origin.xyz)}" quat="{_fmt(q)}" group="{ROBOT_GROUP}" '
              f'contype="1" conaffinity="0" friction="{mu:g} 0.005 0.0001" rgba="0.75 0.6 0.2 1"')
    if col.kind == "box":
        return f'{indent}<geom type="box" size="{_fmt(np.asarray(col.size) / 2.0)}" {common}/>\n'
    if col.kind == "cylinder":
        r, length = col.size
        return f'{indent}<geom type="cylinder" size="{r:g} {length / 2.0:g}" {common}/>\n'
    if col.kind == "sphere":
        return f'{indent}<geom type="sphere" size="{col.size[0]:g}" {common}/>\n'
    return ""


def _body_xml(desc: RobotDescription, link_name: str, joint: Optional[Joint], indent: str,
              kv: float, free: bool, spawn_pos=(0.0, 0.0, 0.56), spawn_quat=(1.0, 0.0, 0.0, 0.0)) -> str:
    link = desc.links[link_name]
    if joint is None:
        pos, quat = spawn_pos, spawn_quat
    else:
        pos, quat = joint.origin.xyz, joint.origin.quat
    out = f'{indent}<body name="{link_name}" pos="{_fmt(pos)}" quat="{_fmt(quat)}">\n'
    ind = indent + "  "
    if free:
        out += f'{ind}<freejoint name="root"/>\n'
    if link.inertial is not None and link.inertial.mass > 0.0:
        ine = link.inertial
        ixx, iyy, izz, ixy, ixz, iyz = ine.inertia
        I = np.array([[ixx, ixy, ixz], [ixy, iyy, iyz], [ixz, iyz, izz]])
        R = rpy_to_matrix(*ine.origin.rpy)
        I = R @ I @ R.T                      # inertia frame rotated into the link frame
        out += (f'{ind}<inertial pos="{_fmt(ine.origin.xyz)}" mass="{ine.mass:.10g}" '
                f'fullinertia="{_fmt((I[0, 0], I[1, 1], I[2, 2], I[0, 1], I[0, 2], I[1, 2]))}"/>\n')
    if joint is not None and joint.type in ("revolute", "continuous"):
        rng = ""
        if joint.type == "revolute" and math.isfinite(joint.lower) and math.isfinite(joint.upper):
            rng = f' range="{joint.lower:.10g} {joint.upper:.10g}" limited="true"'
        out += (f'{ind}<joint name="{joint.name}" type="hinge" axis="{_fmt(joint.axis)}"{rng} '
                f'damping="{joint.damping:g}" frictionloss="{joint.friction:g}" '
                f'solreflimit="{_fmt(LIMIT_SOLREF)}"/>\n')
    mu = link.mu if link.mu is not None else 1.0      # SDF default surface friction mu = 1
    for col in link.collisions:
        out += _geom_xml(col, mu, ind)
    out += f'{ind}<site name="{link_name}_site" pos="0 0 0" size="0.005" group="3"/>\n'
    for cj in desc.children(link_name):
        out += _body_xml(desc, cj.child, cj, ind, kv, False)
    out += f"{indent}</body>\n"
    return out


def robot_mjcf_body(desc: RobotDescription, kv: float = SERVO_KV, spawn_pos=(0.0, 0.0, 0.56),
                    spawn_yaw: float = 0.0) -> str:
    q = rpy_to_quat(0.0, 0.0, spawn_yaw)
    return _body_xml(desc, desc.root, None, "    ", kv, True, spawn_pos, q)


def servo_mode(spec: "ServoSpec", servo: str = "urdf") -> str:
    """Actuation of one joint: ``servo`` "urdf" follows the plugin block
    (``use_velocity_commands``), "velocity" / "force" override it (what-if)."""
    if servo == "urdf":
        return spec.mode
    if servo not in ("velocity", "force"):
        raise ValueError(f"servo must be urdf|velocity|force, got {servo!r}")
    return servo


def robot_mjcf_actuators(desc: RobotDescription, kv: float = SERVO_KV, servo: str = "urdf") -> str:
    """One actuator per joint.

    * force mode (gz JointPositionController PID, ``use_velocity_commands``
      false): a plain motor; the PID force is computed every gz step by
      :class:`physics.sim.GzServo`, clamped to ``cmd_min .. cmd_max`` there
      and to the URDF ``effort`` here (DART's joint force limit);
    * velocity mode (``use_velocity_commands`` true): a velocity actuator
      ``kv * (ctrl - qvel)`` with the force limited to the URDF effort, the
      command ``clamp((q_t - q) / dt, cmd_min, cmd_max)`` comes from GzServo."""
    out = ""
    for j in desc.actuated_joints():
        s = desc.servos.get(j.name, ServoSpec(j.name))
        eff = j.effort if math.isfinite(j.effort) else 1e6
        if servo_mode(s, servo) == "force":
            out += (f'    <motor name="{j.name}_servo" joint="{j.name}" ctrllimited="true" '
                    f'ctrlrange="{-eff:g} {eff:g}"/>\n')
        else:
            cmax = min(max(abs(s.cmd_max), abs(s.cmd_min)), 1e6)
            out += (f'    <velocity name="{j.name}_servo" joint="{j.name}" kv="{kv:g}" ctrllimited="true" '
                    f'ctrlrange="{-cmax:g} {cmax:g}" forcelimited="true" forcerange="{-eff:g} {eff:g}"/>\n')
    return out


def build_mjcf(desc: RobotDescription, terrain_xml: str = "", kv: float = SERVO_KV,
               spawn_pos=(0.0, 0.0, 0.56), spawn_yaw: float = 0.0, payload: Optional[dict] = None,
               dt: float = PHYSICS_DT, servo: str = "urdf") -> str:
    """Complete MJCF: options, terrain (worldbody geoms) and the robot.

    payload: optional ``{"mass": kg, "pos": (x, y, z), "size": (sx, sy, sz)}``
    welded on top of the trunk (base frame)."""
    robot = robot_mjcf_body(desc, kv, spawn_pos, spawn_yaw)
    if payload:
        sz = np.asarray(payload.get("size", (0.20, 0.15, 0.06)), dtype=float)
        m = float(payload["mass"])
        ixx = m * (sz[1] ** 2 + sz[2] ** 2) / 12.0
        iyy = m * (sz[0] ** 2 + sz[2] ** 2) / 12.0
        izz = m * (sz[0] ** 2 + sz[1] ** 2) / 12.0
        body = (f'      <body name="payload" pos="{_fmt(payload.get("pos", (0.0, 0.0, 0.10)))}">\n'
                f'        <inertial pos="0 0 0" mass="{m:g}" diaginertia="{ixx:g} {iyy:g} {izz:g}"/>\n'
                f'        <geom type="box" size="{_fmt(sz / 2)}" group="{ROBOT_GROUP}" contype="1" '
                f'conaffinity="0" rgba="0.2 0.5 0.8 1" mass="0"/>\n'
                f'      </body>\n')
        # insert right after the trunk's free joint line
        marker = '<freejoint name="root"/>\n'
        robot = robot.replace(marker, marker + body, 1)
    return f"""<mujoco model="{desc.name}_physics_check">
  <compiler angle="radian" autolimits="true" inertiafromgeom="false"/>
  <option timestep="{dt:g}" integrator="implicitfast" cone="elliptic" impratio="{IMPRATIO:g}" gravity="0 0 -9.81"/>
  <default>
    <geom solref="{_fmt(CONTACT_SOLREF)}" solimp="{_fmt(CONTACT_SOLIMP)}" condim="3"/>
  </default>
  <visual><global offwidth="800" offheight="600"/></visual>
  <worldbody>
{terrain_xml}{robot}  </worldbody>
  <actuator>
{robot_mjcf_actuators(desc, kv, servo)}  </actuator>
</mujoco>
"""
