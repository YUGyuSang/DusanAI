"""
Navigation map access for Module 3 (ROS free).

The binding 2-D map is ``simulation/maps/plant_map.yaml`` (generated by
``tools/generate_world.py``).  Every Module-3 node and the offline evaluation
load it through :func:`load_nav_map`.  When the file does not exist yet (fresh
checkout before the world generator ran, unit tests on Windows) an
*equivalent* occupancy grid is rasterised directly from
``world_layout.yaml`` with the same conventions as the generator:

* everything outside the factory / corridor interiors is a wall (occupied),
* the east doorway connects the hall with the corridor,
* machines, drums, pallets, pipe-rack supports, gauge stands and the small
  vertical pipe stubs are OCCUPIED,
* pipes, rubble, steel plates, the low platform, stairs and the ramp are FREE
  (the legged robot walks over them).
"""
from __future__ import annotations

import math
import os
from typing import Optional, Tuple

import numpy as np

from dusan_common.grid_map import OccupancyGridMap
from dusan_common.layout import Layout

#: obstacle types that block the 2-D map (others are traversable debris)
BLOCKING_OBSTACLES = ("pallet", "drum")
#: footprint of the pallet mesh model (x, y) before yaw
PALLET_SIZE = (1.22, 1.40)


def _fill_rect(occ, grid, x0, y0, x1, y1, value):
    """Set every cell whose centre lies inside the axis aligned rectangle."""
    res = grid.resolution
    ix0 = int(math.ceil((min(x0, x1) - grid.origin_x) / res - 0.5))
    ix1 = int(math.floor((max(x0, x1) - grid.origin_x) / res - 0.5))
    iy0 = int(math.ceil((min(y0, y1) - grid.origin_y) / res - 0.5))
    iy1 = int(math.floor((max(y0, y1) - grid.origin_y) / res - 0.5))
    ix0, iy0 = max(ix0, 0), max(iy0, 0)
    ix1, iy1 = min(ix1, occ.shape[1] - 1), min(iy1, occ.shape[0] - 1)
    if ix1 >= ix0 and iy1 >= iy0:
        occ[iy0:iy1 + 1, ix0:ix1 + 1] = value


def _cell_centres(grid):
    xs = grid.origin_x + (np.arange(grid.width) + 0.5) * grid.resolution
    ys = grid.origin_y + (np.arange(grid.height) + 0.5) * grid.resolution
    return np.meshgrid(xs, ys)


def _fill_oriented_box(occ, X, Y, cx, cy, sx, sy, yaw, value, pad=0.0):
    """Cells inside a yawed box of size (sx, sy) centred at (cx, cy)."""
    c, s = math.cos(yaw), math.sin(yaw)
    dx, dy = X - cx, Y - cy
    lx = c * dx + s * dy          # world -> box frame
    ly = -s * dx + c * dy
    m = (np.abs(lx) <= sx / 2 + pad) & (np.abs(ly) <= sy / 2 + pad)
    occ[m] = value


def _fill_disc(occ, X, Y, cx, cy, r, value):
    occ[(X - cx) ** 2 + (Y - cy) ** 2 <= r * r] = value


def build_layout_map(layout: Layout, resolution: Optional[float] = None) -> OccupancyGridMap:
    """Rasterise world_layout.yaml into an OccupancyGridMap (0 free / 100 occupied)."""
    nm = layout.get("nav_map", {}) or {}
    res = float(resolution or nm.get("resolution", 0.10))
    bx0, by0, bx1, by1 = nm.get("bounds", [-10.6, -9.6, 64.2, 9.6])
    w = int(round((bx1 - bx0) / res))
    h = int(round((by1 - by0) / res))
    occ = np.full((h, w), 100, dtype=np.int8)
    grid = OccupancyGridMap(occ, res, bx0, by0)
    X, Y = _cell_centres(grid)

    fac = layout["factory"]["interior"]
    _fill_rect(occ, grid, fac["x_min"], fac["y_min"], fac["x_max"], fac["y_max"], 0)
    cor = layout.get("corridor", {}).get("interior")
    if cor:
        _fill_rect(occ, grid, cor["x_min"], cor["y_min"], cor["x_max"], cor["y_max"], 0)
        # east doorway: the opening is wider than the corridor, the wall stub
        # between x_max(factory) and x_min(corridor) is removed over the
        # corridor width.
        op = layout["factory"].get("east_opening", {})
        y0 = max(op.get("y_min", cor["y_min"]), cor["y_min"])
        y1 = min(op.get("y_max", cor["y_max"]), cor["y_max"])
        _fill_rect(occ, grid, fac["x_max"] - res, y0, cor["x_min"] + res, y1, 0)

    for m in layout.get("machines", []):
        fp = m["footprint"]
        _fill_rect(occ, grid, fp["x_min"], fp["y_min"], fp["x_max"], fp["y_max"], 100)

    for ob in layout.obstacles:
        t = ob.get("type")
        if t == "drum":
            _fill_disc(occ, X, Y, ob["center"][0], ob["center"][1], float(ob.get("radius", 0.3)), 100)
        elif t == "pallet":
            _fill_oriented_box(occ, X, Y, ob["center"][0], ob["center"][1],
                               PALLET_SIZE[0], PALLET_SIZE[1], float(ob.get("yaw", 0.0)), 100)

    rack = layout.get("pipe_rack")
    if rack:
        sx, sy = rack.get("support_size", [0.12, 0.5, 1.5])[:2]
        y_rack = rack["pipe"]["start"][1]
        for xs in rack.get("supports_x", []):
            _fill_oriented_box(occ, X, Y, xs, y_rack, sx, sy, 0.0, 100)

    # gauge stands: a small post behind every dial face
    for g in layout.gauges:
        px, py = g["position"][0], g["position"][1]
        nx_, ny_ = g.get("normal", [0, 0, 0])[:2]
        _fill_disc(occ, X, Y, px - 0.06 * nx_, py - 0.06 * ny_, 0.08, 100)

    stub = layout.get("corridor_pipe_stub")
    if stub:
        _fill_disc(occ, X, Y, stub["position"][0], stub["position"][1], float(stub.get("radius", 0.06)), 100)
    leak = layout.gas_leak
    if leak.get("valve_prop"):
        vp = leak["valve_prop"]
        _fill_disc(occ, X, Y, vp[0], vp[1], 0.10, 100)

    grid.occ = occ
    return grid


def resolve_layout(layout_file: str = "") -> Layout:
    """Layout from an explicit path or the default share/source location."""
    return Layout.load(layout_file or None)


def load_nav_map(map_yaml: str = "", layout: Optional[Layout] = None,
                 allow_fallback: bool = True) -> Tuple[OccupancyGridMap, str]:
    """Load the navigation map.

    Order: explicit ``map_yaml`` -> ``layout.nav_map_yaml()`` -> rasterised
    layout (if ``allow_fallback``).  Returns ``(grid, description)``.
    """
    layout = layout or Layout.load()
    candidates = [p for p in (map_yaml, layout.nav_map_yaml()) if p]
    for p in candidates:
        if os.path.exists(p):
            return OccupancyGridMap.load(p), p
    if not allow_fallback:
        raise FileNotFoundError(f"navigation map not found: {candidates}")
    return build_layout_map(layout), "layout-rasterised"


def map_fingerprint(grid: OccupancyGridMap) -> tuple:
    """Cheap identity of a map (shape, origin, resolution, occupied count) used
    to skip expensive rebuilds when a latched /map is re-delivered."""
    return (grid.width, grid.height, round(grid.resolution, 6), round(grid.origin_x, 4),
            round(grid.origin_y, 4), int(np.count_nonzero(grid.occ >= 50)),
            int(np.count_nonzero(grid.occ < 0)))
